#nullable disable

using System.Drawing;

namespace System.Windows.Forms.Tests;

public class ToolStripDropDownMenuTests
{
    [WinFormsFact]
    public void ToolStripDropDownMenu_Constructor()
    {
        using ToolStripDropDownMenu menu = new();

        Assert.NotNull(menu);
    }

    [WinFormsFact]
    public void ToolStripDropDownMenu_ConstructorOwnerItemBool()
    {
        using ToolStripButton owner = new();
        bool isAutoGenerated = true;

        using ToolStripDropDownMenu menu = new(owner, isAutoGenerated);

        Assert.NotNull(menu);
        Assert.Equal(owner, menu.OwnerItem);
        Assert.True(menu.IsAutoGenerated);
    }

    [WinFormsFact]
    public void ContextMenuStrip_ScrollInternal_Up_SkipsUnavailableItem()
    {
        // Regression test for https://github.com/dotnet/winforms/issues/7635.
        // Layout: [0:available, 1:available, 2:UNAVAILABLE, 3:available, 4:available, 5:available]
        // Scrolling down twice lands on item 3, whose raw predecessor (item 2) is unavailable.
        // Scrolling back up once must then skip item 2 and land on item 1 -- the previous
        // *available* item -- instead of silently failing to move (the reported bug: the raw
        // adjacent item's stale bounds coincide with item 3's own bounds, producing delta == 0
        // and leaving the user stuck unable to scroll back to earlier items).
        using ContextMenuStrip menu = new()
        {
            MaximumSize = new Size(150, 60)
        };

        for (int i = 0; i < 6; i++)
        {
            menu.Items.Add(new ToolStripMenuItem($"Item{i}"));
        }

        menu.Items[2].Available = false;

        menu.Show(new Point(10, 10));

        Assert.True(menu.RequiresScrollButtons);

        dynamic accessor = menu.TestAccessor.Dynamic;

        accessor.ScrollInternal(false);
        accessor.ScrollInternal(false);

        int indexBeforeScrollUp = accessor._indexOfFirstDisplayedItem;
        Assert.Equal(3, indexBeforeScrollUp);

        int topBeforeScrollUp = menu.Items[3].Bounds.Top;

        accessor.ScrollInternal(true);

        int indexAfterScrollUp = accessor._indexOfFirstDisplayedItem;
        int topAfterScrollUp = menu.Items[3].Bounds.Top;

        // The view must actually have moved (not stuck at item 3), must never
        // land on the hidden item 2, and must land on the previous available item (1).
        Assert.NotEqual(topBeforeScrollUp, topAfterScrollUp);
        Assert.NotEqual(2, indexAfterScrollUp);
        Assert.Equal(1, indexAfterScrollUp);
        Assert.True(menu.Items[indexAfterScrollUp].Available);

        menu.Close();
    }
}
